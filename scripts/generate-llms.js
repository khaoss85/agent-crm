/**
 * Reads the structured job index if it exists. Its shape is owned elsewhere, so this
 * accepts the reasonable forms and degrades to "absent" rather than crashing on one
 * it does not recognise.
 * @param {string} path
 */
function readJobIndex(path) {
  if (!existsSync(path)) return { present: false, total: 0, counts: {} };

  let data;
  try {
    data = JSON.parse(readFileSync(path, 'utf8'));
  } catch (error) {
    problems.push(`docs/benchmarks/jobs.json: invalid JSON — ${error.message}`);
    return { present: false, total: 0, counts: {} };
  }

  const list = Array.isArray(data) ? data : (data.jobs ?? data.entries ?? data.rows);
  if (!Array.isArray(list) || list.length === 0) {
    problems.push('docs/benchmarks/jobs.json: no job array found (expected an array, or a jobs/entries/rows property). Remove the file or fix its shape.');
    return { present: false, total: 0, counts: {} };
  }

  /** @type {Record<string, number>} */
  const counts = {};
  for (const job of list) {
    const status = String(job?.status ?? '').trim().toLowerCase();
    if (!status) continue;
    counts[status] = (counts[status] ?? 0) + 1;
  }

  return { present: true, total: list.length, counts };
}

/**
 * A one-line description: curated where the judgement matters, derived from the
 * document's own opening otherwise, so a new document is never left undescribed.
 * @param {string} path
 * @returns {string}
 */
function describe(path) {
  if (path in DESCRIPTIONS) return DESCRIPTIONS[path];
  const full = join(root, path);
  if (!existsSync(full)) {
    problems.push(`${path}: listed in llms.txt but not on disk. Update scripts/generate-llms.js or restore the file.`);
    return 'missing';
  }
  return tokenizeBrand(firstSentence(readFileSync(full, 'utf8')));
}

/** Top-level docs plus the benchmark catalogue, sorted, so the output is stable. */
function discoverDocuments() {
  const found = readdirSync(join(root, 'docs'))
    .filter((name) => name.endsWith('.md'))
    .map((name) => `docs/${name}`);
  found.push('docs/benchmarks/CRM_JTBD_MATRIX.md');
  return found.sort();
}

/**
 * The first real sentence after the H1 — skipping headings, blank lines and the
 * blockquote marker — trimmed to a line's worth.
 * @param {string} markdown
 */
function firstSentence(markdown) {
  const collected = [];
  let pastTitle = false;

  for (const line of markdown.split('\n')) {
    const trimmed = line.trim();
    if (!pastTitle) {
      if (trimmed.startsWith('# ')) pastTitle = true;
      continue;
    }
    if (!trimmed) {
      if (collected.length) break;
      continue;
    }
    if (/^#{1,6}\s/.test(trimmed)) {
      if (collected.length) break;
      continue;
    }
    collected.push(trimmed.replace(/^>\s?/, ''));
  }

  const text = collected
    .join(' ')
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/[*_`]/g, '')
    .replace(/\s+/g, ' ')
    .trim();

  const match = text.match(/^(.*?[.!?])(\s|$)/);
  let sentence = match ? match[1] : text;
  if (sentence.length > 110) sentence = `${sentence.slice(0, 107).replace(/\s+\S*$/, '')}…`;
  return sentence || 'no description available';
}

/**
 * The first document that evidences an entry — the link target for its line. A
 * ledger entry evidenced only by tests or repo facts has no document to point at.
 * @param {Record<string, any> | undefined} evidence
 * @returns {string | null}
 */
function primaryDoc(evidence) {
  return (evidence?.docs ?? [])[0] ?? null;
}

/**
 * The paths behind a ledger entry. `repoFacts` are deliberately left out: they are
 * prose assertions rather than locations, and they restate the entry's own sentence.
 * @param {Record<string, any> | undefined} evidence
 */
function evidencePaths(evidence) {
  const paths = [
    ...(evidence?.jtbd ? [evidence.jtbd] : []),
    ...(evidence?.tests ?? []),
    ...(evidence?.docs ?? []),
  ];
  return paths.length ? paths.map((path) => `\`${path}\``) : ['no path evidence — see `site/claims.json`'];
}

// ---------------------------------------------------------------- text utilities

/**
 * Turns the working title back into brand tokens. The name is undecided, so an
 * inlined document must not carry it literally into a generated asset — the token
 * is the sanctioned way to say it, and it survives the rename.
 * @param {string} text
 */
function tokenizeBrand(text) {
  return text
    .replaceAll(brand.name.value, '{{brand.name}}')
    .replaceAll(brand.name.slug, '{{brand.slug}}');
}

/**
 * Pushes every heading down by `levels`, skipping fenced code blocks so a shell
 * comment is never mistaken for a heading.
 * @param {string} text
 * @param {number} levels
 */
function demoteHeadings(text, levels) {
  const prefix = '#'.repeat(levels);
  let fenced = false;

  return text.split('\n').map((line) => {
    if (/^\s*```/.test(line)) {
      fenced = !fenced;
      return line;
    }
    if (fenced) return line;
    return /^#{1,6}\s/.test(line) ? `${prefix}${line}` : line;
  }).join('\n');
}

/**
 * A last guard before either file is written.
 *
 * `scripts/site-check.js` is the gate that matters — it runs over the built site and
 * fails the release. These patterns are kept in step with its §4 and §5 so a
 * regenerated file never reaches that gate broken, and so the failure names the
 * generator rather than a build three steps later.
 *
 * @param {string} name
 * @param {string} text
 */
function guard(name, text) {
  const brandLeaks = [
    { pattern: /agent[-\s]?crm/i, why: 'the working title — use {{brand.name}} or {{brand.slug}}' },
    { pattern: /\bhttps?:\/\/(?!localhost)[\w.-]*(?:\.dev|\.com|\.io|\.ai)\b/i, why: 'an absolute external URL' },
    { pattern: /\baccordo|pactio|vinculo|relato\b/i, why: 'a shortlisted name that has not been chosen' },
  ];
  const overclaims = [
    { pattern: /\bproduction[-\s]ready\b/i, why: 'there is no authentication, tenancy or RBAC (L-01)' },
    { pattern: /\benterprise[-\s]grade\b/i, why: 'unfalsifiable' },
    { pattern: /\b(soc\s?2|iso\s?27001|hipaa|gdpr[-\s]compliant)\b/i, why: 'no compliance posture exists' },
    { pattern: /\bbank[-\s]grade\b/i, why: 'unfalsifiable' },
    { pattern: /\b(fastest|best|leading|world[-\s]class|revolutionary|game[-\s]chang)/i, why: 'unfalsifiable superlative' },
    { pattern: /\bguarantee[sd]?\b/i, why: 'nothing here is guaranteed, least of all model behaviour' },
    { pattern: /\b\d{1,3}(\.\d+)?%\s*(success|SABR|build rate|pass rate)/i, why: 'the benchmark has not been run (L-03)' },
    { pattern: /\bfully autonomous\b/i, why: 'human approval is the product' },
    { pattern: /\breplaces? salesforce\b/i, why: 'explicitly not the positioning' },
    { pattern: /\bzero[-\s]config\b/i, why: 'you write manifests and policies; that is configuration' },
    { pattern: /\btrusted by\b/i, why: 'there are no users to cite' },
  ];

  const lines = text.split('\n');
  for (let index = 0; index < lines.length; index += 1) {
    const stripped = lines[index].replace(/\{\{[^}]+\}\}/g, '');
    for (const leak of brandLeaks) {
      if (leak.pattern.test(stripped)) {
        problems.push(`${name}:${index + 1}: hardcodes ${leak.why}\n      ${lines[index].trim().slice(0, 120)}`);
      }
    }
  }

  for (const overclaim of overclaims) {
    const match = text.match(overclaim.pattern);
    if (match) problems.push(`${name}: overclaim "${match[0]}" — ${overclaim.why}`);
  }
}

