/**
 * The whole file. `full` adds the inlined documents; everything before them is
 * identical in both variants, so a reader who fetched the short one is never told
 * something different by the long one.
 * @param {{ full: boolean }} options
 * @returns {string}
 */
function compose({ full }) {
  const blocks = [
    header(full),
    statusSection(),
    whatItIsSection(),
    doesNotExistSection(),
    provenSection(full),
    jobCoverageSection(),
    answersSection(answersIndex),
    commandsSection(),
    readingOrderSection(),
    citationSection(),
    optionalSection(full),
  ];

  if (full) {
    const { inlined, omitted } = inlineSections(blocks.join('\n\n'));
    blocks.push(...inlined, omissionsSection(omitted));
  }

  return `${blocks.join('\n\n').replace(/\n{3,}/g, '\n\n').trim()}\n`;
}

