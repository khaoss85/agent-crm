/**
 * Generates `site/assets/llms.txt` and `site/assets/llms-full.txt`.
 *
 * These two files are the task-time retrieval surface: a model mid-task fetches one
 * of them and decides whether to recommend this framework. That decision is only as
 * good as the file is current, and a hand-written llms.txt is a file that starts
 * lying at the next merge — a capability lands, a limitation is lifted, a document is
 * renamed, and the copy still says what was true in March.
 *
 * So nothing here is asserted by hand. The content is composed from:
 *
 *   site/claims.json            capabilities, each with the limitation that travels
 *                               with it, plus the standing limitations
 *   site/brand.json             tokens only — the public name is undecided, and no
 *                               generated byte may hardcode one
 *   the documents on disk       the reading order is checked against the filesystem,
 *                               and an uncatalogued doc is described from its own text
 *                               rather than silently omitted
 *   docs/benchmarks/jobs.json   the structured JTBD index, if it exists; when it does
 *                               not, the file says so instead of guessing
 *
 * The output keeps the `{{token}}` convention because `scripts/site-build.js` renders
 * these assets into `site/dist`. Brand values stay tokens all the way to the build.
 *
 * Run:
 *   node scripts/generate-llms.js            write both files, report their byte sizes
 *   node scripts/generate-llms.js --check    exit 1 if a committed file is stale
 */

